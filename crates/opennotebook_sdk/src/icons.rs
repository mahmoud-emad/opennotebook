/// The inner markup of an icon, or `None` for a name not vendored here.
pub fn icon(name: &str) -> Option<&'static str> {
    ICONS
        .binary_search_by(|(n, _)| n.cmp(&name))
        .ok()
        .map(|i| ICONS[i].1)
}

/// Every icon as one hidden SVG sprite of `<symbol id="bi-NAME">`, for a page
/// that is plain HTML and draws icons with `<svg><use href="#bi-NAME"/></svg>`.
pub fn sprite() -> String {
    let mut s = String::from(
        r#"<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">"#,
    );
    for (name, inner) in ICONS {
        s.push_str(&format!(
            r#"<symbol id="bi-{name}" viewBox="0 0 16 16">{inner}</symbol>"#
        ));
    }
    s.push_str("</svg>");
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_are_sorted_and_unique_so_lookup_finds_them() {
        assert!(ICONS.windows(2).all(|w| w[0].0 < w[1].0));
        for (n, _) in ICONS {
            assert!(icon(n).is_some(), "{n}");
        }
        assert!(icon("not-an-icon").is_none());
    }

    #[test]
    fn every_icon_is_drawable_markup() {
        for (n, inner) in ICONS {
            assert!(
                inner.starts_with('<') && inner.contains("d=\""),
                "{n}: {inner}"
            );
            assert!(!inner.contains("<script"), "{n}");
        }
    }

    #[test]
    fn the_sprite_holds_every_icon_as_a_symbol() {
        let s = sprite();
        assert_eq!(s.matches("<symbol ").count(), ICONS.len());
        assert!(s.contains(r#"id="bi-play-fill""#));
    }
}
